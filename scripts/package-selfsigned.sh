#!/bin/zsh

# Build a universal ad-hoc/self-signed preview package. Unlike the production
# release flow, this does not notarize or touch Sparkle/R2.
#
#   scripts/package-selfsigned.sh
#   OUTPUT_BASENAME=kero-0.1.49-preview scripts/package-selfsigned.sh

set -euo pipefail

cd "${0:A:h:h}"

identity="${CODE_SIGN_IDENTITY:--}"
archs="${ARCHS:-arm64 x86_64}"
build_dir="${KERO_PACKAGE_BUILD_DIR:-build/selfsigned}"
derived_data="$build_dir/DerivedData"
app="$derived_data/Build/Products/Release/Kero.app"

need() {
    if ! command -v "$1" >/dev/null 2>&1; then
        print -u2 "missing required command: $1"
        exit 1
    fi
}

need xcodebuild
need codesign
need lipo
need plutil
need hdiutil
need shasum
need python3
need strings

rm -rf "$build_dir/dmg"
mkdir -p "$build_dir"

xcodebuild \
    -project Kero.xcodeproj \
    -scheme kero \
    -configuration Release \
    -destination 'generic/platform=macOS' \
    -derivedDataPath "$derived_data" \
    ARCHS="$archs" \
    ONLY_ACTIVE_ARCH=NO \
    CODE_SIGNING_ALLOWED=YES \
    CODE_SIGNING_REQUIRED=YES \
    CODE_SIGN_IDENTITY="$identity" \
    CODE_SIGN_STYLE=Manual \
    ENABLE_USER_SCRIPT_SANDBOXING=NO \
    build

[[ -d "$app" ]] || { print -u2 "built app not found: $app"; exit 1; }

# Remote renderer sessions depend on this custom Ghostty config option to
# suppress replies generated by the local renderer. An upstream binary rejects
# the entire config (including its color theme) when the option is missing.
ghostty_library="$derived_data/Build/Products/Release/libghostty.a"
[[ -f "$ghostty_library" ]] || { print -u2 "Ghostty library not found: $ghostty_library"; exit 1; }
if ! strings "$ghostty_library" | grep -F 'kero-renderer-only' >/dev/null; then
    print -u2 'Ghostty library lacks the Kero renderer patch; build it with scripts/build-daemon-ghostty.sh first'
    exit 1
fi

version="$(plutil -extract CFBundleShortVersionString raw "$app/Contents/Info.plist")"
build="$(plutil -extract CFBundleVersion raw "$app/Contents/Info.plist")"
output_basename="${OUTPUT_BASENAME:-kero-$version-selfsigned}"
dmg="$build_dir/$output_basename.dmg"
sha="$build_dir/$output_basename.sha256"
staging="$build_dir/dmg"

rm -f "$sha"

# The Rust daemon and bundled frameworks are nested code. Deep-sign the finished
# app here as a final packaging pass; a shallow outer signature can leave those
# helpers unsealed and make launch or strict verification fail.
timestamp_args=(--timestamp=none)
if [[ "$identity" != "-" ]]; then
    timestamp_args=(--timestamp)
fi

codesign --force --deep --sign "$identity" \
    --entitlements kero/kero.entitlements \
    "${timestamp_args[@]}" \
    --generate-entitlement-der \
    "$app"

# Self-signed previews deliberately omit hardened runtime. Developer ID
# distribution gets it from the normal release export instead.
if codesign -dv "$app" 2>&1 | grep -q 'flags=.*runtime'; then
    print -u2 'main executable unexpectedly has the hardened runtime flag'
    exit 1
fi

# Keep this deep too: a shallow verify can pass even when nested code is stale
# or unsigned.
codesign --verify --deep --strict --verbose=2 "$app"
[[ "$(lipo -archs "$app/Contents/MacOS/kero")" == *arm64* ]] ||
    { print -u2 "expected an arm64 slice"; exit 1; }
[[ "$(lipo -archs "$app/Contents/MacOS/kero")" == *x86_64* ]] ||
    { print -u2 "expected an x86_64 slice"; exit 1; }

mkdir -p "$staging"
ditto "$app" "$staging/Kero.app"
ln -s /Applications "$staging/Applications"
codesign --verify --deep --strict --verbose=2 "$staging/Kero.app"
cmp "$app/Contents/MacOS/kero" "$staging/Kero.app/Contents/MacOS/kero"

# A failed create can leave this output image attached without a mount point.
# Detach only that image before retrying or verifying the completed package.
detach_output_image() {
    local device
    device="$(hdiutil info -plist | python3 -c '
import os, plistlib, re, sys
target = os.path.realpath(sys.argv[1])
images = plistlib.loads(sys.stdin.buffer.read()).get("images", [])
for image in images:
    if os.path.realpath(image.get("image-path", "")) != target:
        continue
    for entity in image.get("system-entities", []):
        entry = entity.get("dev-entry", "")
        if re.fullmatch(r"/dev/disk[0-9]+", entry):
            print(entry)
            sys.exit()
' "$dmg")"
    if [[ -n "$device" ]]; then
        hdiutil detach "$device"
    fi
}

# hdiutil can briefly report the staging directory as busy while Spotlight or
# LaunchServices releases the freshly signed app. Retry instead of failing the
# otherwise-complete build.
created=false
for attempt in {1..3}; do
    detach_output_image
    rm -f "$dmg"
    if hdiutil create \
        -volname 'Kero Self-Signed Preview' \
        -srcfolder "$staging" \
        -ov \
        -format UDZO \
        "$dmg"
    then
        created=true
        break
    fi
    print "hdiutil create failed (attempt $attempt); retrying…"
    sleep 2
done
[[ "$created" == true ]] || { print -u2 'could not create DMG'; exit 1; }

detach_output_image
codesign --force --sign "$identity" "${timestamp_args[@]}" "$dmg"
shasum -a 256 "$dmg" > "$sha"

hdiutil verify "$dmg"
codesign --verify --strict --verbose=2 "$dmg"

print "Packaged Kero $version (build $build):"
print "  app : $app"
print "  dmg : $dmg"
print "  sha : $sha"
